import mongoose from "mongoose";


// ======================================================
// =============== NOTIFICATION SCHEMA ==================
// ======================================================

const notificationSchema = new mongoose.Schema(

  {

    // ======================================================
    // ================= RECEIVER USER ======================
    // ======================================================

    userId: {

      type:
        mongoose.Schema.Types.ObjectId,

      ref: "User",

      required: true,
    },


    // ======================================================
    // ================= MESSAGE ============================
    // ======================================================

    message: {

      type: String,

      required: true,
    },


    // ======================================================
    // ================= TYPE ===============================
    // ======================================================

    type: {

      type: String,

      enum: [

        "assignment",

        "accepted",

        "declined",

        "resolved",

        "general",

        "alert",
      ],

      default: "general",
    },


    // ======================================================
    // ================= READ STATUS ========================
    // ======================================================

    isRead: {

      type: Boolean,

      default: false,
    },


    // ======================================================
    // ================= RELATED REPORT =====================
    // ======================================================

    relatedReportId: {

      type:
        mongoose.Schema.Types.ObjectId,

      ref: "Report",

      default: null,
    },


    // ======================================================
    // ================= SENDER USER ========================
    // ======================================================

    senderId: {

      type:
        mongoose.Schema.Types.ObjectId,

      ref: "User",

      default: null,
    },


    // ======================================================
    // ================= ACTION REQUIRED ====================
    // ======================================================

    requiresAction: {

      type: Boolean,

      default: false,
    },


    // ======================================================
    // ================= ACTION STATUS ======================
    // ======================================================

    actionTaken: {

      type: Boolean,

      default: false,
    },


    // ======================================================
    // ================= ACTION TYPE ========================
    // ======================================================

    actionType: {

      type: String,

      enum: [

        "accepted",

        "declined",

        ""
      ],

      default: "",
    },

  },


  // ======================================================
  // ================= TIMESTAMPS =========================
  // ======================================================

  {
    timestamps: true,
  }
);


// ======================================================
// ================= EXPORT MODEL =======================
// ======================================================

export default mongoose.model(

  "Notification",

  notificationSchema
);